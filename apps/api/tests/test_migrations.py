"""Migrations: they build exactly the models' schema, every step can be undone, the data they
move arrives, and they render as SQL for review."""

from __future__ import annotations

import asyncio
import io

from alembic import command
from alembic.script import ScriptDirectory
from sqlalchemy import text
from sqlalchemy.ext.asyncio import create_async_engine
from sqlalchemy.pool import NullPool

from sef_api.migrations import alembic_config
from sef_api.models import StoredInvoice

TABLES = {
    "alembic_version",
    "organizations",
    "users",
    "memberships",
    "invitations",
    "refresh_tokens",
    "invoices",
    "api_keys",
    "jobs",
    "corpus_documents",
    "corpus_passages",
}


def tables(database_url: str) -> set[str]:
    async def query() -> set[str]:
        engine = create_async_engine(database_url, poolclass=NullPool)
        try:
            async with engine.connect() as connection:
                result = await connection.execute(
                    text("SELECT tablename FROM pg_tables WHERE schemaname = 'public'")
                )
                return set(result.scalars())
        finally:
            await engine.dispose()

    return asyncio.run(query())


async def run(database_url: str, *statements: str) -> list[object]:
    """Run ``statements`` in one transaction and commit; what the last one returned."""
    engine = create_async_engine(database_url, poolclass=NullPool)
    try:
        async with engine.begin() as connection:
            returned: list[object] = []
            for statement in statements:
                result = await connection.execute(text(statement))
                returned = list(result.scalars()) if result.returns_rows else []
            return returned
    finally:
        await engine.dispose()


def test_the_migrations_build_exactly_the_schema_of_the_models(empty_database_url: str) -> None:
    config = alembic_config(empty_database_url)

    command.upgrade(config, "head")

    assert tables(empty_database_url) == TABLES
    command.check(config)  # raises AutogenerateDiffsDetected when models and migrations differ


def test_all_migrations_can_be_undone_and_applied_again(empty_database_url: str) -> None:
    config = alembic_config(empty_database_url)
    command.upgrade(config, "head")

    command.downgrade(config, "base")
    assert tables(empty_database_url) == {"alembic_version"}

    command.upgrade(config, "head")
    assert tables(empty_database_url) == TABLES


def test_each_migration_can_be_undone_one_step_at_a_time(empty_database_url: str) -> None:
    config = alembic_config(empty_database_url)
    revisions = [script.revision for script in ScriptDirectory.from_config(config).walk_revisions()]

    for revision in reversed(revisions):
        command.upgrade(config, revision)
        command.downgrade(config, "-1")
        command.upgrade(config, revision)

    command.check(config)


def test_an_invoice_stored_before_0007_was_last_validated_when_it_was_stored(
    empty_database_url: str,
) -> None:
    config = alembic_config(empty_database_url)
    command.upgrade(config, "0006")
    stored = "2026-10-05 09:30:00+00"
    asyncio.run(
        run(
            empty_database_url,
            "INSERT INTO organizations (name) VALUES ('Primer')",
            "INSERT INTO invoices (organization_id, created_at, profile, valid, report,"
            " report_size, content, size, sha256)"
            f" SELECT id, '{stored}', 'srb', false, '{{}}', 2, 'x', 1, repeat('0', 64)"
            " FROM organizations",
        )
    )

    command.upgrade(config, "0007")

    assert asyncio.run(
        run(empty_database_url, "SELECT validated_at = created_at FROM invoices")
    ) == [True]


INVALID_INVOICES = "ix_invoices_invalid_organization_id_created_at_id"


def test_the_invalid_invoices_have_the_index_the_model_declares(database_url: str) -> None:
    """Alembic compares an index's name and columns with the model's, not its predicate."""
    (definition,) = asyncio.run(
        run(database_url, f"SELECT indexdef FROM pg_indexes WHERE indexname = '{INVALID_INVOICES}'")
    )
    (declared,) = [
        index
        for index in StoredInvoice.metadata.tables["invoices"].indexes
        if index.name == INVALID_INVOICES
    ]

    assert str(definition).endswith(
        "USING btree (organization_id, created_at, id) WHERE (NOT valid)"
    )
    assert [column.name for column in declared.columns] == ["organization_id", "created_at", "id"]
    assert str(declared.dialect_options["postgresql"]["where"]) == "NOT valid"


def test_undoing_0009_drops_the_index_of_the_invalid_invoices(empty_database_url: str) -> None:
    config = alembic_config(empty_database_url)
    command.upgrade(config, "0009")

    command.downgrade(config, "0008")

    indexes = f"SELECT indexname FROM pg_indexes WHERE indexname = '{INVALID_INVOICES}'"
    assert asyncio.run(run(empty_database_url, indexes)) == []


def test_the_revision_ids_are_sequence_numbers() -> None:
    config = alembic_config("postgresql+asyncpg://reviewer@localhost/sef")
    revisions = [script.revision for script in ScriptDirectory.from_config(config).walk_revisions()]

    assert sorted(revisions) == [f"{number:04d}" for number in range(1, len(revisions) + 1)]


def test_the_migrations_render_as_sql_for_review() -> None:
    output = io.StringIO()

    command.upgrade(
        alembic_config("postgresql+asyncpg://reviewer@localhost/sef", output=output),
        "head",
        sql=True,
    )

    sql = output.getvalue()
    for table in (
        "organizations",
        "users",
        "memberships",
        "refresh_tokens",
        "invitations",
        "invoices",
        "corpus_documents",
        "corpus_passages",
    ):
        assert f"CREATE TABLE {table}" in sql
    assert "ON DELETE CASCADE" in sql
    assert "CREATE EXTENSION IF NOT EXISTS vector" in sql
    index = "ix_invoices_invalid_organization_id_created_at_id"
    assert (  # outside the transaction, holding no writes back, after what a failure left
        f"COMMIT;\n\nDROP INDEX CONCURRENTLY IF EXISTS {index};\n\n"
        f"CREATE INDEX CONCURRENTLY {index} ON invoices (organization_id, created_at, id) "
        "WHERE NOT valid;\n\nBEGIN;"
    ) in sql


def test_the_corpus_is_searched_through_indexes_of_its_own_kinds(database_url: str) -> None:
    definitions = asyncio.run(
        run(database_url, "SELECT indexdef FROM pg_indexes WHERE tablename = 'corpus_passages'")
    )

    assert any("USING hnsw (embedding vector_cosine_ops)" in str(d) for d in definitions)
    assert any("USING gin (search_text gin_trgm_ops)" in str(d) for d in definitions)
