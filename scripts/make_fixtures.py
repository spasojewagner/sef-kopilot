"""Generate the mutation fixtures.

A mutation fixture is a synthetic invoice with one deliberate mistake of the kind an ERP or an
integration makes: a PIB with a wrong check digit, a VAT rate SEF does not know, a total that
does not add up, a date in the local format. Each is made from a base invoice in
``fixtures/invoices/synthetic/`` and the text edits in :data:`MUTATIONS`, and written to
``fixtures/invoices/synthetic/mutations/`` with a header that states the mistake and what the
SRB profile reports for it.

The fixtures are generated, never edited by hand; the tests fail when one is out of date.
Usage::

    uv run python scripts/make_fixtures.py      # or: make fixtures
"""

from __future__ import annotations

import argparse
import re
import textwrap
from collections import Counter
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Final

REPOSITORY_ROOT: Final = Path(__file__).resolve().parents[1]
SYNTHETIC: Final = "fixtures/invoices/synthetic"
MUTATIONS_DIR: Final = f"{SYNTHETIC}/mutations"

_NAME = re.compile(r"[a-z0-9]+(-[a-z0-9]+)*")
_HEADER = re.compile(r"\A(<\?xml[^>]*\?>\n)<!--.*?-->\n", re.DOTALL)


@dataclass(frozen=True)
class Mutation:
    """One deliberate mistake in a base invoice, and what the SRB profile reports for it."""

    name: str
    base: str
    mistake: str
    edits: tuple[tuple[str, str], ...]
    expect: tuple[str, ...]

    def __post_init__(self) -> None:
        if _NAME.fullmatch(self.name) is None:
            raise ValueError(f"{self.name!r}: a mutation name is lowercase words and hyphens")
        if "--" in self.mistake:
            raise ValueError(f"{self.name}: the mistake goes into an XML comment, no '--'")
        if not self.edits or not self.expect:
            raise ValueError(f"{self.name}: a mutation has edits and expected rules")

    @property
    def file(self) -> str:
        return f"{MUTATIONS_DIR}/{self.name}.xml"

    def header(self) -> str:
        counts = Counter(self.expect)
        reported = ", ".join(
            f"{rule} ({count})" if count > 1 else rule for rule, count in sorted(counts.items())
        )
        lines = [
            f"Generated by scripts/make_fixtures.py from {self.base}; do not edit.",
            *textwrap.wrap(f"Mistake: {self.mistake}", width=92),
            f"The srb profile reports: {reported}.",
        ]
        return "<!--\n" + "".join(f"  {line}\n" for line in lines) + "-->\n"


def mutate(base: str, mutation: Mutation) -> str:
    """The base document with the mutation's edits applied and its header in front."""
    match = _HEADER.match(base)
    if match is None:
        raise ValueError(f"{mutation.base} must start with an XML declaration and a comment")
    text = base[match.end() :]
    for old, new in mutation.edits:
        count = text.count(old)
        if count != 1:
            raise ValueError(
                f"{mutation.name}: {old!r} occurs {count} times in {mutation.base}, not once"
            )
        text = text.replace(old, new)
    return match.group(1) + mutation.header() + text


def generated(root: Path = REPOSITORY_ROOT) -> dict[str, str]:
    """Every mutation fixture's path (relative to ``root``) and content."""
    bases: dict[str, str] = {}
    files: dict[str, str] = {}
    for mutation in MUTATIONS:
        if mutation.base not in bases:
            bases[mutation.base] = (root / SYNTHETIC / mutation.base).read_text(encoding="utf-8")
        files[mutation.file] = mutate(bases[mutation.base], mutation)
    return files


def write_mutations(root: Path = REPOSITORY_ROOT) -> dict[str, str]:
    """Write the mutation fixtures and remove those the catalogue no longer has."""
    files = generated(root)
    directory = root / MUTATIONS_DIR
    directory.mkdir(parents=True, exist_ok=True)
    for stale in directory.glob("*.xml"):
        if f"{MUTATIONS_DIR}/{stale.name}" not in files:
            stale.unlink()
    for name, text in files.items():
        (root / name).write_text(text, encoding="utf-8", newline="\n")
    return files


def main(argv: Sequence[str] | None = None, *, root: Path = REPOSITORY_ROOT) -> int:
    argparse.ArgumentParser(description="Write the mutation fixtures.").parse_args(argv)
    files = write_mutations(root)
    print(f"{len(files)} mutation fixtures in {MUTATIONS_DIR}/")
    return 0


