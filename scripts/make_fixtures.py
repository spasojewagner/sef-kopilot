def _vat(
    category: str, rate: str, tax: str, total: str, exemption: str = ""
) -> tuple[tuple[str, str], ...]:
    """Edits that change the minimal invoice's only VAT category, rate and the amounts."""
    return (
        (_TAX_TOTAL.format("2400.00"), _TAX_TOTAL.format(tax)),
        (_SUBTOTAL_TAX.format("2400.00"), _SUBTOTAL_TAX.format(tax)),
        (
            _SUBTOTAL_CATEGORY.format("S", "20"),
            _SUBTOTAL_CATEGORY.format(category, rate) + exemption,
        ),
        (_LINE_CATEGORY.format("S", "20"), _LINE_CATEGORY.format(category, rate)),
        (_TOTALS.format("14400.00"), _TOTALS.format(total)),
    )


def _exempt(
    code: str | None = None, reason: str | None = None, category: str = "E"
) -> tuple[tuple[str, str], ...]:
    """Edits that make the minimal invoice's only line exempt, with a code or a reason."""
    exemption = ""
    if code is not None:
        exemption += f"\n        <cbc:TaxExemptionReasonCode>{code}</cbc:TaxExemptionReasonCode>"
    if reason is not None:
        exemption += f"\n        <cbc:TaxExemptionReason>{reason}</cbc:TaxExemptionReason>"
    return _vat(category, "0", "0.00", "12000.00", exemption)


