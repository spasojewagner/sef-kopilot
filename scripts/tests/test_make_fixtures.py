"""Tests for scripts/make_fixtures.py: the catalogue, the edits, the files it writes."""

from __future__ import annotations

import json
import shutil
from pathlib import Path

import pytest

import make_fixtures
from einvoice_core.pipeline import SetAsideViolation, ValidationReport
from einvoice_core.rulesets import RulesetNotFoundError, ruleset_path
from einvoice_core.srb import RULES
from einvoice_core.violations import Severity, Violation
from make_fixtures import (
    MUTATIONS,
    MUTATIONS_DIR,
    REPOSITORY_ROOT,
    SYNTHETIC,
    Mutation,
    corpus,
    generated,
    mutate,
    verdict,
    write_mutations,
)


def _fetched() -> bool:
    try:
        for package in make_fixtures.PACKAGES:
            ruleset_path(package)
    except RulesetNotFoundError:
        return False
    return True


needs_rule_sets = pytest.mark.skipif(not _fetched(), reason="rule sets not fetched")

BASE = (
    '<?xml version="1.0" encoding="UTF-8"?>\n<!--\n  A base.\n-->\n<Invoice><ID>1</ID></Invoice>\n'
)


def mutation(**change: object) -> Mutation:
    fields: dict[str, object] = {
        "name": "srb-009-typo",
        "base": "base.xml",
        "mistake": "a typo in the PIB.",
        "edits": (("<ID>1<", "<ID>2<"),),
        "expect": ("SRB-009", "SRB-009"),
    }
    return Mutation(**(fields | change))  # type: ignore[arg-type]


def copy_bases(root: Path) -> None:
    (root / SYNTHETIC).mkdir(parents=True)
    for base in {m.base for m in MUTATIONS}:
        shutil.copy(REPOSITORY_ROOT / SYNTHETIC / base, root / SYNTHETIC / base)


def test_the_committed_mutation_fixtures_are_up_to_date() -> None:
    files = generated()
    on_disk = {
        f"{MUTATIONS_DIR}/{path.name}": path.read_text(encoding="utf-8")
        for path in (REPOSITORY_ROOT / MUTATIONS_DIR).glob("*.xml")
    }

    assert sorted(on_disk) == sorted(files), "run `make fixtures`"
    for name, text in files.items():
        assert on_disk[name] == text, f"{name} is out of date: run `make fixtures`"


def test_mutation_names_are_unique() -> None:
    names = [m.name for m in MUTATIONS]

    assert len(names) == len(set(names))


def test_every_srb_cius_rule_is_the_target_of_a_mutation() -> None:
    targets = {rule for m in MUTATIONS for rule in m.expect}

    assert {rule.id for rule in RULES} <= targets


def test_the_header_replaces_the_base_comment_and_states_the_mistake() -> None:
    assert mutate(BASE, mutation()) == (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        "<!--\n"
        "  Generated by scripts/make_fixtures.py from base.xml; do not edit.\n"
        "  Mistake: a typo in the PIB.\n"
        "  The srb profile reports: SRB-009 (2).\n"
        "-->\n"
        "<Invoice><ID>2</ID></Invoice>\n"
    )


def test_a_long_mistake_is_wrapped_in_the_header() -> None:
    text = mutate(BASE, mutation(mistake="word " * 30, expect=("BR-06",)))

    lines = text.splitlines()
    assert max(len(line) for line in lines) <= 94
    assert lines[-3] == "  The srb profile reports: BR-06."


@pytest.mark.parametrize("count", [0, 2])
def test_an_edit_must_match_exactly_once(count: int) -> None:
    base = BASE.replace("<ID>1</ID>", "<ID>1</ID>" * count)

    with pytest.raises(ValueError, match=f"occurs {count} times in base.xml, not once"):
        mutate(base, mutation())


def test_a_base_starts_with_a_declaration_and_a_comment() -> None:
    with pytest.raises(ValueError, match="must start with an XML declaration and a comment"):
        mutate("<Invoice/>\n", mutation())


@pytest.mark.parametrize(
    ("change", "message"),
    [
        ({"name": "SRB_009"}, "lowercase words and hyphens"),
        ({"mistake": "a -- b"}, "no '--'"),
        ({"edits": ()}, "edits and expected rules"),
        ({"expect": ()}, "edits and expected rules"),
    ],
)
def test_a_mutation_is_checked_when_it_is_defined(change: dict[str, object], message: str) -> None:
    with pytest.raises(ValueError, match=message):
        mutation(**change)


def test_writing_the_fixtures_removes_stale_ones(tmp_path: Path) -> None:
    copy_bases(tmp_path)
    stale = tmp_path / MUTATIONS_DIR / "srb-000-gone.xml"
    stale.parent.mkdir(parents=True)
    stale.write_text("<Invoice/>\n", encoding="utf-8")

    files = write_mutations(tmp_path)

    assert not stale.exists()
    written = sorted((tmp_path / MUTATIONS_DIR).glob("*.xml"))
    assert [f"{MUTATIONS_DIR}/{path.name}" for path in written] == sorted(files)
    assert all(b"\r\n" not in path.read_bytes() for path in written)


